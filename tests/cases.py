"""IPVarch test cases.

Each case is a dict:
    name       : id shown on pass/fail
    args       : argv passed after the binary name
    exit       : expected exit code (default 0)
    must       : substrings required in stdout ('stderr:' prefix targets stderr)
    must_not   : substrings forbidden in stdout
    validator  : key of a structural validator run on stdout (see runner.py)
    repeat     : run the case this many times (for random/statistical checks)
"""

def case(name, args, exit=0, must=None, must_not=None, validator=None, repeat=1):
    return {
        "name": name,
        "args": args,
        "exit": exit,
        "must": must or [],
        "must_not": must_not or [],
        "validator": validator,
        "repeat": repeat,
    }

